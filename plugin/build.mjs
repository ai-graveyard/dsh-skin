import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { getSkinDirectories } from './discover-skins.mjs'

const directories = await getSkinDirectories()
if (directories.length === 0) throw new Error('No themes found.')

const themes = await Promise.all(directories.map(async (directory) => {
  const read = (file) => readFile(join(directory, file), 'utf8')
  const [listing, css, tokens] = await Promise.all([
    read('skin.json').then(JSON.parse),
    read('skin.css'),
    read('tokens.json').then(JSON.parse),
  ])
  return {
    id: listing.slug,
    name: listing.name,
    nameZh: listing.nameZh,
    colors: listing.colors,
    preview: listing.preview,
    order: listing.order,
    css,
    tokens: Object.fromEntries(
      Object.entries(tokens).map(([name, value]) => [name, { light: value, dark: value }]),
    ),
  }
}))
themes.sort((a, b) => a.order - b.order)

const pkg = JSON.parse(await readFile(new URL('./package.json', import.meta.url), 'utf8'))
const pickerCss = (await readFile(new URL('./picker.css', import.meta.url), 'utf8')).trimEnd()
const source = (await readFile(new URL('./client-source.js', import.meta.url), 'utf8')).trimEnd()
const client = `// Generated by build.mjs.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    const PACKAGE_ID = ${JSON.stringify(pkg.name)}
    const PICKER_CSS = ${JSON.stringify(pickerCss)}
    const THEMES = [
${themes.map((theme) => `      ${JSON.stringify(theme)},`).join('\n')}
    ]
${source.split('\n').map((line) => line ? `    ${line}` : '').join('\n')}
  },
})
`

const target = new URL('./client.js', import.meta.url)
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== client) {
    console.error('plugin/client.js is stale. Run pnpm run build:plugin.')
    process.exitCode = 1
  }
} else {
  await writeFile(target, client)
  console.log(`Built ${pkg.name} with ${themes.length} themes.`)
}
